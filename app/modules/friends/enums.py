from enum import StrEnum


class FriendshipStatus(StrEnum):
    """Статусы дружеской связи между пользователями.

    Запись хранится в каноническом виде (``user_id < friend_id``),
    поэтому статус описывает состояние пары, а не направления заявки.
    Направление заявки задаётся полем ``initiator_id``.
    """

    PENDING = 'pending'  # Заявка отправлена инициатором, ожидает ответа второй стороны
    ACCEPTED = 'accepted'  # Заявка принята, пользователи являются друзьями
    DECLINED = 'declined'  # Заявка отклонена второй стороной (блокирует повторную отправку)
